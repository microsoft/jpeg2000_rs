use jpeg2000_decoder::ResourceLimits;

#[cfg(test)]
#[path = "../fuzz_targets/structured_framing.rs"]
mod structured_framing_tests;

pub fn resource_limits() -> ResourceLimits {
    ResourceLimits::default()
        .with_maximum_input_bytes(1 << 20)
        .unwrap()
        .with_maximum_metadata_bytes(1 << 20)
        .unwrap()
        .with_maximum_decoded_bytes(4 << 20)
        .unwrap()
        .with_maximum_code_blocks(256)
        .unwrap()
        .with_maximum_packets(4096)
        .unwrap()
        .with_maximum_jpip_fragments(256)
        .unwrap()
        .with_maximum_work_units(1_000_000)
        .unwrap()
}

#[cfg(test)]
mod tests {
    use super::*;
    use jpeg2000_decoder::{DecodeError, DecodeOptions, decode_codestream};

    #[test]
    fn fuzz_profile_rejects_large_grid_before_exhausting_process_memory() {
        let input = [
            0xff, 0x4f, 0xff, 0x51, 0x00, 0x29, 0x00, 0x00, 0x00, 0x00, 0x02, 0x01, 0x00, 0x00,
            0x52, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x01,
            0xcd, 0x00, 0x04, 0x81, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01,
            0x07, 0x01, 0x01, 0xff, 0x52, 0x00, 0x0c, 0x00, 0x02, 0x00, 0x01, 0x00, 0x00, 0x00,
            0x00, 0x00, 0x01, 0xff, 0x5c, 0x00, 0x04, 0x00, 0x40, 0xff, 0x90, 0x00, 0x0a, 0x00,
            0x00, 0x00, 0x00, 0x00, 0x0f, 0x00, 0x01, 0xff, 0x93, 0x00, 0xff, 0xd9,
        ];
        assert!(matches!(
            decode_codestream(&input, &DecodeOptions::new(resource_limits())),
            Err(DecodeError::LimitExceeded { .. })
        ));
    }
}
